// Trechos de 32 blocos: [linha, coluna, conteúdo]. O piso fica nas linhas 12/13.
// Só os elementos indicados substituem o ar/piso; os saltos mantêm a escala original.
function segment32(parts, indoor = false) {
  const rows = Array.from({ length: 14 }, (_, y) =>
    y >= 12 ? G32 : indoor && y < 2 ? Z2 : E32);
  for (const [y, x, tiles] of parts) {
    if (y < 0 || y >= 14 || x < 0 || x + tiles.length > 32) throw new Error('Trecho fora dos limites');
    rows[y] = rows[y].slice(0, x) + tiles + rows[y].slice(x + tiles.length);
  }
  return rows;
}

